#!/usr/bin/env node
// Exercise the reading controls in the shared abx browser session.
const { execFileSync } = require('child_process');
const assert = require('node:assert/strict');
const base = process.argv[2] || 'http://127.0.0.1:4010';
const run = (...args) => execFileSync('abx', args, { encoding: 'utf8', timeout: 30000 }).trim();
const js = expression => JSON.parse(run('js', `JSON.stringify(${expression})`));
const article = base + '/posts/paseo-changed-my-multi-account-codex-setup';
run('goto', article);
run('js', "localStorage.removeItem('toc-closed'); localStorage.removeItem('theme')");
run('viewport', '1600x1000');
run('reload');
assert.equal(js("document.querySelector('.toc-toggle').getAttribute('aria-expanded')"), 'true');
assert.equal(js("document.querySelectorAll('.toc-list a').length"), js("document.querySelectorAll('.c-post__body h2').length"));
assert(js("[...document.querySelectorAll('.toc-list a')].every(a => document.getElementById(decodeURIComponent(a.hash.slice(1))))"));
const before = js("document.querySelector('.c-post').getBoundingClientRect().left");
assert(js("document.querySelector('.toc-panel').getBoundingClientRect().right < document.querySelector('.c-post').getBoundingClientRect().left"));
run('click', '.toc-toggle');
assert.equal(js("document.querySelector('.toc-panel').hidden"), true);
assert.equal(js("document.querySelector('.c-post').getBoundingClientRect().left"), before);
run('reload');
assert.equal(js("document.querySelector('.toc-panel').hidden"), true);
run('click', '.toc-toggle');
run('click', '.toc-list li:nth-child(3) a');
assert(js("location.hash.length > 1"));
assert.equal(js("document.activeElement.tagName"), 'H2');
assert(js("document.querySelector('.toc-list a[aria-current]')?.hash === location.hash"));
run('js', "document.querySelector('.toc-toggle').focus()");
run('press', 'Escape');
assert.equal(js("document.querySelector('.toc-panel').hidden"), true);
assert.equal(js("document.activeElement.className"), 'toc-toggle');
run('click', '.toc-toggle');
run('viewport', '390x844');
assert.equal(js("document.querySelector('.toc-panel').hidden"), true);
run('click', '.toc-toggle');
assert.equal(js("document.querySelector('.toc-panel').hidden"), false);
run('click', '.toc-list li:nth-child(2) a');
assert.equal(js("document.querySelector('.toc-panel').hidden"), true);
assert(js("document.documentElement.scrollWidth <= innerWidth"));
run('click', '.theme-toggle');
assert.equal(js("getComputedStyle(document.documentElement).backgroundColor"), 'rgb(31, 30, 29)');
assert.equal(js("getComputedStyle(document.body).color"), 'rgb(240, 238, 230)');
run('goto', base);
assert.equal(js("document.querySelector('#essays').textContent"), 'Essays');
assert.equal(js("document.querySelector('#notes').textContent"), 'Notes & guides');
assert.equal(js("document.querySelector('main > :first-child').className"), 'intro');
assert(js("document.querySelector('.intro').textContent.includes('Edi Hasaj is a software engineer')"));
assert.equal(js("!!document.querySelector('.post-toc')"), false);
console.log('Reading controls passed: desktop, mobile, anchors, keyboard, persistence, palette, and homepage sections.');
