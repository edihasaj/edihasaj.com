#!/usr/bin/env ruby
# Generate static social cards before publishing to GitHub Pages.
require 'jekyll'
require 'digest'
require 'cgi'
require 'fileutils'
require 'open3'
require 'tempfile'

ROOT = File.expand_path('..', __dir__)
VERSION = 'paper-v1'

# Conservative line lengths leave room for wide serif glyphs.
def title_lines(title)
  words = title.split.flat_map { |word| word.scan(/.{1,28}/) }
  words.each_with_object([]) do |word, lines|
    if !lines.empty? && lines.last.length + word.length + 1 <= 28
      lines[-1] += " #{word}"
    else
      lines << word
    end
  end
end

def card_svg(title, home: false)
  lines = home ? ['Edi', 'Hasaj'] : title_lines(title)
  size = home ? 120 : [66, (380.0 / [lines.length, 1].max / 1.18).floor].min
  line_height = size * 1.18
  first_y = 490 - (lines.length - 1) * line_height
  text = lines.each_with_index.map do |line, index|
    %(<text x="88" y="#{first_y + index * line_height}">#{CGI.escapeHTML(line)}</text>)
  end.join
  byline = home ? '' : '<text x="90" y="564" font-size="26" fill="#68645c">Edi Hasaj</text>'
  <<~SVG
    <svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
      <rect width="1200" height="630" fill="#f0eee6"/>
      <g font-family="Georgia, Liberation Serif, serif" font-size="#{size}" fill="#242320">#{text}#{byline}</g>
    </svg>
  SVG
end

if $PROGRAM_NAME == __FILE__
  Dir.chdir(ROOT) do
    site = Jekyll::Site.new(Jekyll.configuration('quiet' => true))
    site.reset
    site.read
    entries = (site.pages + site.collections.values.flat_map(&:docs)).select do |page|
      %w[default page post topic landing].include?(page.data['layout']) && page.data['title'] && page.data['og_image'] != false
    end
    cards = entries.to_h do |page|
      title = page.url == '/' ? site.config['title'] : page.data['title'].to_s
      digest = Digest::SHA256.hexdigest([VERSION, page.url, title].join("\n"))[0, 16]
      [page.url, { 'title' => title, 'image' => "/images/og/#{digest}.png" }]
    end.sort.to_h
    manifest = "# Generated by bundle exec ruby bin/generate-og.rb. Do not edit.\n" + cards.to_yaml
    manifest_path = '_data/og_images.yml'
    if ARGV.include?('--check')
      missing = cards.values.reject { |card| File.file?(".#{card['image']}") }
      abort 'Social cards are stale. Run bundle exec ruby bin/generate-og.rb.' unless File.exist?(manifest_path) && File.read(manifest_path) == manifest && missing.empty?
      puts "Social cards current (#{cards.length})."
      exit
    end
    FileUtils.mkdir_p('images/og')
    cards.each do |url, card|
      output = ".#{card['image']}"
      next if File.exist?(output) && !ARGV.include?('--force')
      Tempfile.create(['edi-og', '.svg']) do |file|
        file.write(card_svg(card['title'], home: url == '/'))
        file.flush
        _, error, status = Open3.capture3('rsvg-convert', '--output', output, file.path)
        abort "Social card failed: #{error}" unless status.success?
      end
    end
    File.write(manifest_path, manifest)
    puts "Generated #{cards.length} social cards. Commit images/og and #{manifest_path}."
  end
end
